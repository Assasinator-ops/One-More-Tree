	/**
	 * Get a sanitized SVG icon by semantic slug.
	 *
	 * @since 1.0.0
	 *
	 * @param string $slug Icon slug.
	 * @return string
	 */
	public static function get_svg( $slug ) {

		$icons = self::get_icons();
		$slug  = sanitize_key( $slug );

		if ( ! isset( $icons[ $slug ] ) ) {
			return '';
		}

		return wp_kses( $icons[ $slug ], self::get_allowed_svg_html() );
	}

